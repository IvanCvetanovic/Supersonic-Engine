static void testEveryPlatformComputesTheTablesBits() {
    int wrong = 0;
    for (const Row& row : kGolden) {
        const uint32_t got = bitsOf(evaluate(row));
        if (got == row.expected) continue;
        ++wrong;
        char message[160];
        std::snprintf(message, sizeof message, "%s(%08x, %08x) = %08x, the table says %08x", nameOf(row.fn),
                      static_cast<unsigned>(row.a), static_cast<unsigned>(row.b), static_cast<unsigned>(got),
                      static_cast<unsigned>(row.expected));
        CHECK_MSG(false, message);
    }
    CHECK_MSG(wrong == 0, std::to_string(wrong) + " golden row(s) differ on this platform");
}

static void testTheCallThatPartedTheTwoPlatformsIsSettled() {
    // Tick 29 of the canonical scene: glibc said bd005aa8, the UCRT bd005aa7,
    // and the correctly rounded answer is the UCRT's.
    CHECK_MSG(bitsOf(DetMath::atan2(fromBits(0xbd002dd0u), fromBits(0x3f7f9124u))) == 0xbd005aa7u,
              "the tick-29 atan2 is the correctly rounded value on every platform");

    // And the damping factor every rotating body takes every step, which the
    // runtimes happened to agree on - now by construction rather than luck.
    CHECK_MSG(bitsOf(DetMath::pow(0.95f, 1.0f / 60.0f)) == 0x3f7fc7ffu, "pow(0.95, 1/60) is 3f7fc7ff");
}

static void testItStaysWithinAnUlpOrTwoOfThisPlatformsLibm() {
    // Not the determinism check - the table is - but the one that catches a
    // wrong quadrant, a wrong branch or a wrong constant, all of which the
    // table could share with the transcription that made it.
    long long worstSin = 0, worstCos = 0, worstAsin = 0, worstAtan2 = 0, worstPow = 0;
    for (int i = -4000; i <= 4000; ++i) {
        const float x = static_cast<float>(i) * 0.0025f; // [-10, 10]
        worstSin = std::max(worstSin, ulpDistance(DetMath::sin(x), std::sin(x)));
        worstCos = std::max(worstCos, ulpDistance(DetMath::cos(x), std::cos(x)));
        const float u = static_cast<float>(i) / 4000.0f; // [-1, 1]
        worstAsin = std::max(worstAsin, ulpDistance(DetMath::asin(u), std::asin(u)));
    }
    for (int i = -60; i <= 60; ++i) {
        for (int j = -60; j <= 60; ++j) {
            const float y = static_cast<float>(i) * 0.083f;
            const float x = static_cast<float>(j) * 0.071f;
            if (x == 0.0f && y == 0.0f) continue;
            worstAtan2 = std::max(worstAtan2, ulpDistance(DetMath::atan2(y, x), std::atan2(y, x)));
        }
    }
    for (int i = 1; i <= 200; ++i) {
        for (int j = -40; j <= 40; ++j) {
            const float b = static_cast<float>(i) * 0.02f;
            const float e = static_cast<float>(j) * 0.07f;
            worstPow = std::max(worstPow, ulpDistance(DetMath::pow(b, e), std::pow(b, e)));
        }
    }
    CHECK_MSG(worstSin <= 2, "sin within 2 ulp of libm, worst " + std::to_string(worstSin));
    CHECK_MSG(worstCos <= 2, "cos within 2 ulp of libm, worst " + std::to_string(worstCos));
    CHECK_MSG(worstAsin <= 2, "asin within 2 ulp of libm, worst " + std::to_string(worstAsin));
    CHECK_MSG(worstAtan2 <= 2, "atan2 within 2 ulp of libm, worst " + std::to_string(worstAtan2));
    CHECK_MSG(worstPow <= 2, "pow within 2 ulp of libm, worst " + std::to_string(worstPow));
}

static void testTheEdgesAreCs() {
    const float inf = std::numeric_limits<float>::infinity();
    const float nan = std::numeric_limits<float>::quiet_NaN();

    CHECK_MSG(DetMath::sin(-0.0f) == 0.0f && std::signbit(DetMath::sin(-0.0f)), "sin(-0) is -0");
    CHECK(DetMath::cos(0.0f) == 1.0f);
    CHECK(std::isnan(DetMath::sin(inf)));
    CHECK(std::isnan(DetMath::cos(nan)));

    CHECK(bitsOf(DetMath::asin(1.0f)) == 0x3fc90fdbu);
    CHECK(bitsOf(DetMath::asin(-1.0f)) == 0xbfc90fdbu);
    CHECK(std::isnan(DetMath::asin(1.5f)));
    CHECK_MSG(std::signbit(DetMath::asin(-0.0f)), "asin(-0) is -0");

    CHECK(bitsOf(DetMath::atan2(0.0f, 0.0f)) == 0x00000000u);
    CHECK(bitsOf(DetMath::atan2(-0.0f, 0.0f)) == 0x80000000u);
    CHECK(bitsOf(DetMath::atan2(0.0f, -0.0f)) == 0x40490fdbu);
    CHECK(bitsOf(DetMath::atan2(-0.0f, -0.0f)) == 0xc0490fdbu);
    CHECK(bitsOf(DetMath::atan2(1.0f, 0.0f)) == 0x3fc90fdbu);
    CHECK(bitsOf(DetMath::atan2(-1.0f, -0.0f)) == 0xbfc90fdbu);
    CHECK(bitsOf(DetMath::atan2(inf, inf)) == 0x3f490fdbu);
    CHECK(bitsOf(DetMath::atan2(-inf, -inf)) == 0xc016cbe4u);
    CHECK(bitsOf(DetMath::atan2(1.0f, -inf)) == 0x40490fdbu);
    CHECK(bitsOf(DetMath::atan2(2.0f, inf)) == 0x00000000u);

    CHECK(DetMath::pow(3.0f, 0.0f) == 1.0f);
    CHECK(DetMath::pow(0.0f, 2.0f) == 0.0f);
    CHECK(DetMath::pow(0.0f, -1.0f) == inf);
    CHECK(DetMath::pow(0.5f, inf) == 0.0f);
    CHECK(DetMath::pow(2.0f, inf) == inf);
    // Documented: a negative base is not what DetMath::pow is for.
    CHECK_MSG(std::isnan(DetMath::pow(-2.0f, 2.0f)), "a negative base gives NaN, as the header says");
}

static void testAngleAxisIsGlmsFormula() {
    struct Case {
        float angle;
        glm::vec3 axis;
    };
    const Case cases[] = {
        {0.3f, glm::vec3(0.0f, 1.0f, 0.0f)},
        {-2.1f, glm::normalize(glm::vec3(1.0f, 2.0f, -0.5f))},
        {3.0f, glm::normalize(glm::vec3(-0.2f, 0.1f, 0.9f))},
    };
    for (const Case& c : cases) {
        const glm::quat mine = DetMath::angleAxis(c.angle, c.axis);
        const glm::quat theirs = glm::angleAxis(c.angle, c.axis);
        const float worst = std::max(std::max(std::fabs(mine.w - theirs.w), std::fabs(mine.x - theirs.x)),
                                     std::max(std::fabs(mine.y - theirs.y), std::fabs(mine.z - theirs.z)));
        CHECK_MSG(worst <= 1e-6f, "angleAxis(" + std::to_string(c.angle) + ") matches glm's to 1e-6, worst " +
                                      std::to_string(worst));
    }
}

void runTests() {
    testEveryPlatformComputesTheTablesBits();
    testTheCallThatPartedTheTwoPlatformsIsSettled();
    testItStaysWithinAnUlpOrTwoOfThisPlatformsLibm();
    testTheEdgesAreCs();
    testAngleAxisIsGlmsFormula();
}

