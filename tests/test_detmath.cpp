// DetMath: the simulation's transcendental functions, which must give the same
// bits on every platform.
//
// They exist because libm does not. test_determinism's canonical scene hashed
// to one number on Windows and another on Linux, and the whole difference was
// one-ulp disagreements between the UCRT and glibc - the first an atan2f in
// EulerFromRotation on tick 29 (docs/planning/2026-09-10-cross-platform-
// determinism.md).
//
// THE GOLDEN TABLE is the heart of this file. It was produced by a Python
// transcription of DetMath.hpp, operation for operation; Python's floats are
// IEEE doubles with no contraction, so the table is what any conforming
// platform computes. A row failing here means this compiler reordered,
// contracted or substituted an operation somewhere in DetMath - which would
// otherwise surface as a replay that stops reproducing on one machine.
//
// The same transcription measured accuracy: over 100,000 random inputs across
// the five functions, every result was the correctly rounded float.

