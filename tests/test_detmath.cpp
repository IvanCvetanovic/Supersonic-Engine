float fromBits(uint32_t bits) {
    float f;
    std::memcpy(&f, &bits, sizeof f);
    return f;
}

uint32_t bitsOf(float f) {
    uint32_t bits;
    std::memcpy(&bits, &f, sizeof bits);
    return bits;
}

const char* nameOf(Fn fn) {
    switch (fn) {
    case Fn::Sin: return "sin";
    case Fn::Cos: return "cos";
    case Fn::Asin: return "asin";
    case Fn::Atan2: return "atan2";
    case Fn::Pow: return "pow";
    }
    return "?";
}

float evaluate(const Row& row) {
    const float a = fromBits(row.a);
    const float b = fromBits(row.b);
    switch (row.fn) {
    case Fn::Sin: return DetMath::sin(a);
    case Fn::Cos: return DetMath::cos(a);
    case Fn::Asin: return DetMath::asin(a);
    case Fn::Atan2: return DetMath::atan2(a, b);
    case Fn::Pow: return DetMath::pow(a, b);
    }
    return 0.0f;
}

// Distance in representable floats, across zero as well.
long long ulpDistance(float a, float b) {
    auto line = [](float f) {
        const int64_t i = static_cast<int32_t>(bitsOf(f));
        return i < 0 ? static_cast<int64_t>(INT32_MIN) - i : i;
    };
    const long long d = static_cast<long long>(line(a) - line(b));
    return d < 0 ? -d : d;
}

