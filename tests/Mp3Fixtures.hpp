// Three synthetic MP3 streams for test_audio.cpp, embedded so the test needs no
// encoder and no file: computed tones, not anyone's recording.
//
// HOW THEY WERE MADE (authoring time only; nothing here runs an encoder):
//   1. A 16-bit WAV of each sine: sample n of a channel at frequency f and rate r
//      is round(16384 * sin(2 * pi * f * n / r)), for the length given below.
//   2. lame 3.100 (Ubuntu 24.04's `lame` package), with the command line quoted
//      under each array.
//   The bytes below are lame's output, unedited. Regenerating them with another
//   lame gives other bytes, which is why they are kept rather than rebuilt: the
//   test pins what dr_mp3 and Media Foundation do with THESE streams.
//
// What the streams are used to prove is in test_audio.cpp. Two facts about them
// that the tests lean on, both checked when they were made:
//   * Dropping the first (Info) frame of kStereo44k leaves, byte for byte, what
//     `lame -t` writes for the same audio: a stream whose first frame is audio.
//     The tests build that variant by slicing, so it is not stored twice.
//   * The Info frame's frame-count field is the four bytes after "Info" and its
//     four flag bytes, big-endian: the tests overwrite it to say something
//     absurd about the stream's length.
//
// The k...Sha256 strings beside the arrays are documentation: the digest of the
// bytes as lame wrote them, so that a regenerated file can be compared with the
// one the tests were written against. No test reads them; an edit to the bytes is
// caught by the exact lengths, tones and frame counts the tests pin.

